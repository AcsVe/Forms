def seed():
    owner = User.query.filter_by(role='admin').order_by(User.id).first()
    for title, title_en, cat, settings, text in TEMPLATES:
        p = parse(text)
        schema = normalize_schema({'questions': p['questions']})
        if title.startswith('استطلاع آراء الطلبة'):
            qs = schema['questions']
            yes = qs[0]
            secs = [q for q in qs if q['type'] == 'section']
            yes['choices'][0]['goto'] = secs[0]['id']        # نعم ← الأنشطة
            yes['choices'][1]['goto'] = secs[1]['id']        # لا ← الأسباب
            secs[0]['next'] = '__submit__'                   # بعد الأنشطة ← إرسال
        db.session.add(Form(title=title, title_en=title_en, description=p['description'], category=cat,
                            is_template=True, status='draft', owner_id=owner.id if owner else None,
                            schema=schema, settings=dict({'accent': '#0C67EC', 'progress': True}, **settings)))
    db.session.commit()
